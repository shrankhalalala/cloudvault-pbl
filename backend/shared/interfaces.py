"""Integration boundaries for storage, metadata, and notification delivery."""
from typing import Any, Protocol


class ObjectStore(Protocol):
    upload_headers: dict[str, str]
    def presign_put(self, key: str, content_type: str, size: int, expires: int) -> str: ...
    def head(self, key: str, version_id: str | None = None) -> dict[str, Any] | None: ...
    def presign_get(self, key: str, version_id: str, expires: int, filename: str = "download") -> str: ...
    def list_versions(self, key: str, cursor: list[str] | None = None, limit: int = 25) -> dict: ...
    def create_delete_marker(self, key: str) -> str: ...
    def copy_version(self, key: str, version_id: str, operation_id: str, *,
                     source_key: str | None = None, content_type: str) -> dict: ...


class MetadataRepository(Protocol):
    def get(self, owner: str, sort_key: str) -> dict | None: ...
    def get_file(self, owner: str, file_id: str) -> dict | None: ...
    def all(self, owner: str, prefix: str, maximum: int): ...
    def query(self, owner: str, prefix: str, *, limit: int = 100, start: str | None = None,
              descending: bool = False) -> tuple[list[dict], str | None]: ...
    def put(self, owner: str, sort_key: str, row: dict, expected_revision: int | None = None) -> dict: ...
    def increment(self, owner: str, sort_key: str, limit: int, expires_at: int | None = None) -> dict: ...
    def transact(self, changes: list[dict], operation_id: str) -> None: ...


class NotificationPublisher(Protocol):
    def publish(self, subject: str, message: str, deduplication_key: str) -> None: ...
